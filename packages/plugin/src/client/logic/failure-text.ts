/**
 * 给主人看的命令失败原因：去掉开头的英文键名（P75r7，B10）。
 *
 * 为什么需要：核心校验命令参数时，错误文字写成「{参数名}：{原因}」，例如「memoryId：这一条记忆不存在」。
 * 中文部分已经说清了原因，但开头的英文参数名是内部说法，不该出现在主人面前。
 * 记忆页（更正、删除、撤销）与技能库（回退、放回）显示失败原因的地方共用这一个函数；核心的错误文字不改。
 *
 * 规则：文字以「一段由英文字母、数字、点、下划线组成并以英文字母开头的词」加全角冒号开头时，去掉这一段和冒号；
 * 其余情形原样返回（没有键名的、中文开头带冒号的、去掉后什么都不剩的）。
 */

/** 开头的英文键名加全角冒号。 */
const LEADING_KEY = /^[A-Za-z][A-Za-z0-9._]*：/

/** 去掉开头的英文键名；没有键名或去掉后为空时原样返回。 */
export function stripFailureKey(text: string): string {
  const stripped = text.replace(LEADING_KEY, '')
  return stripped.trim() === '' ? text : stripped
}
