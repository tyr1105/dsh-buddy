/**
 * 拼「问题：选定项」的统一写法（P74r14 第 7 节）。
 *
 * 为什么需要：约定里待定项的问题常以问号结尾（「是否限制报名人数？」），原来直接拼成「是否限制报名人数？：限 80 人」，
 * 问号后面接冒号，读起来不通。拼这句话的地方（总管唤醒包、「待你处理」条目正文、按约定答复时显示的依据、约定文件）
 * 都经过这一个函数：先去掉问题末尾的问号（全角「？」和半角「?」，连同其后的空白），再接冒号。
 * 只在拼这句话时去掉，不改存下来的问题原文；约定卡上单独显示问题的地方不受影响。
 */

/**
 * 去掉问题末尾的问号（全角、半角，连同其后的空白）。
 * P74r15：末尾连续多个问号（「是否限制？？」「是否限制?？」，全角半角混用）全部去掉，否则拼出「是否限制？：…」。
 * 问号之间夹着空白（「？ ？」）也算连续。
 */
export function stripQuestionMark(question: string): string {
  return question.replace(/(?:[？?][\s]*)+$/u, '').replace(/[\s]+$/u, '');
}

/** 「问题：选定项」，问题末尾的问号去掉。 */
export function joinQuestion(question: string, answer: string): string {
  return `${stripQuestionMark(question)}：${answer}`;
}
