/**
 * 判断一句话里有没有写时间（P74r7 第 1 节）。
 *
 * 为什么需要：派活时总管用 deliveryItems 指定「交付时核对」的条目。这类条目只能是与交付时间有关的那一条
 * （例如「11 月 17 日 18:00 前交给你验收」），执行者不附证据，由中心在交付时按时间判断。
 * 真实模型曾把「怎样算做完」的全部条目都写进去，结果整件事没有证据、没有核对。
 * 中心用本文件的判断函数检查：条目原文里没有写时间的，不能当作「交付时核对」。
 *
 * 做法：用一组正则覆盖常见写法，只看原文，不读时钟。宁可严一点：单独的「之前」「以前」不算时间
 * （「发布之前确认」不是交付时间），必须同时带着数字、日期或星期。纯函数，可单测。
 */

/** 中文数字（含「两」）。 */
const CN_NUM = '[一二三四五六七八九十两零]';

/** 表示一天中某一段的词（「下午 3 点」里的「下午」）。 */
const PERIOD_WORD = '(?:凌晨|清晨|早上|早晨|上午|中午|下午|傍晚|晚上|夜里|午夜)';

/** 「N 日」「N 号」后面跟这些词，说明这个日期是在说交付时间（P74r15）。 */
const DAY_SUFFIX = '前|之前|以前|当天|当日|上午|下午|晚上|早上|中午|截止|交付|交|下班|提交|完成|上线|发布|验收|给我|给你|为止|之内|以内|内';

/** 「N 点」后面跟这些词，说明这个钟点是在说交付时间（P74r15）。 */
const HOUR_SUFFIX = '前|整|半|之前|以前|左右|钟|一刻|交付|交|更新|提交|完成|上线|发布|验收|给我|给你|截止|下班';

/** 各种时间写法；任何一条命中就算写了时间。 */
const TIME_PATTERNS: readonly RegExp[] = [
  // 完整日期：2026-11-17、2026/11/17、2026 年 11 月、11/17。
  /\d{4}\s*[-/.年]\s*\d{1,2}/,
  /(?<![\d.])\d{1,2}\s*\/\s*\d{1,2}(?![\d.])/,
  // 月和日：11月17日、11 月 17 日、17号之前、3月（含「3 个月内」）。
  // P74r13：「12 月份的账单」不是时间（月后面是「份」）；「7 日留存」「5 号位」「2 号文件」不是时间：
  // 「N 日」「N 号」要有「月」在前（11 月 17 日），或后面跟着「前」「之前」「当天」「上午」「下午」这类时间词。
  /\d{1,2}\s*月(?!份)/,
  /月\s*\d{1,2}\s*[日号]/,
  // P74r15：「17 号交付」「17 日交」「17 日下班前」这类交付时间的写法也算：后面加交、交付、下班、提交、完成、上线、发布、验收、给、为止、内。
  // 「7 日留存」「7 日均值」「5 号位」「第 3 号文件」后面不是这些词，仍然不算。
  new RegExp(`\\d{1,2}\\s*[日号]\\s*(?:${DAY_SUFFIX})`),
  // 前面有「截止」「截至」「到」「最晚」「不晚于」「限」这类词：「截止 17 号」「到 17 号」。
  /(?:截止|截至|最晚|不晚于|不迟于|限|到)\s*(?:\d{1,2}|[一二三四五六七八九十两]{1,3})\s*[日号]/,
  new RegExp(`${CN_NUM}{1,3}\\s*月(?!份)`),
  // 星期：周三、星期三、礼拜三、下周、本周、这周、周末、下周三。
  /周[一二三四五六日天末]/,
  /星期[一二三四五六日天]/,
  /礼拜[一二三四五六日天]/,
  /[上下本这]个?周/,
  // 相对日期：今天、明天、后天、今晚、月底、月初、年底等。
  /今天|明天|后天|大后天|昨天|前天|今晚|明晚|今早|明早|今日|明日|当天|当日|次日|隔天|周内/,
  /月底|月初|月末|年底|年初|年末|季度末|下个月|本月|上个月|这个月/,
  // 几点：18:00、18：00、下午 3 点、18 点前、3 点整、3 点半、18 点 30 分。
  // P74r13：「3 点注意事项」不是时间：「N 点」要有上午、下午这类词在前，或后面跟着「前」「整」「半」「N 分」这类时间词。
  /\d{1,2}\s*[:：]\s*\d{2}/,
  new RegExp(`${PERIOD_WORD}\\s*(?:\\d{1,2}|${CN_NUM}{1,3})\\s*[点時时]`),
  // P74r15：「18 点交」「18 点更新」也算（后面跟交付、更新这类词）；13 到 24 点单独写（「18 点」）一定是钟点，也算；
  // 「3 点注意事项」「2 点改进意见」后面不是这些词，仍然不算。
  new RegExp(`(?:\\d{1,2}|${CN_NUM}{1,3})\\s*[点時时]\\s*(?:${HOUR_SUFFIX}|\\d{1,2}\\s*分|${CN_NUM}{1,3}\\s*分)`),
  /(?<![\d.])(?:1[3-9]|2[0-4])\s*[点時时]/,
  // 一段时间之内：3 天内、48 小时内、三天以内、2 周之内、30 分钟后。
  new RegExp(`(?:\\d+|${CN_NUM}{1,3})\\s*个?\\s*(?:小时|分钟|天|日|周|星期|个月|月|个工作日|工作日)\\s*(?:内|以内|之内|后|之后|前|以前|之前)`),
  // 尽快类的口头语不算；「截止」必须连着数字或日期才算，已由上面的写法覆盖。
];

/** 这句话里写了时间吗？ */
export function hasTimeMention(text: string): boolean {
  const flat = text.replace(/\s+/g, ' ');
  return TIME_PATTERNS.some(pattern => pattern.test(flat));
}
