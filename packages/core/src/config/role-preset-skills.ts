/** 每份清单统一的结尾：写在正文里，队友读 SKILL.md 时能直接看到边界。 */
const NO_NEW_POWER = '这份清单不提高任何工具权限。';

/** 把若干行拼成正文，并补上统一结尾，避免 13 份内容各写各的。 */
function body(lines: readonly string[]): string {
  return [...lines, '', NO_NEW_POWER].join('\n');
}

